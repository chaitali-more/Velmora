export function buildShareUrl(pathname: string, params: Record<string, string | number | boolean | undefined>) {
  if (typeof window === "undefined") {
    return pathname;
  }

  const url = new URL(pathname, window.location.origin);

  Object.entries(params).forEach(([key, value]) => {
    if (value === undefined || value === "") {
      return;
    }

    url.searchParams.set(key, String(value));
  });

  return url.toString();
}

function escapeXml(value: string) {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

export function downloadResultCard(options: {
  title: string;
  filename: string;
  summaryLines: string[];
  footer?: string;
}) {
  const { title, filename, summaryLines, footer = "Generated by Velmora" } = options;
  const safeTitle = escapeXml(title);
  const lines = summaryLines.map((line) => escapeXml(line));
  const safeFooter = escapeXml(footer);

  const resultRows = lines
    .map((line, index) => {
      const separatorIndex = line.indexOf(":");
      const label = separatorIndex > -1 ? line.slice(0, separatorIndex) : `Result ${index + 1}`;
      const value = separatorIndex > -1 ? line.slice(separatorIndex + 1).trim() : line;
      const y = 258 + index * 72;

      return `
        <g>
          <line x1="104" y1="${y - 24}" x2="1096" y2="${y - 24}" stroke="#e2e8f0" stroke-width="2" />
          <text x="104" y="${y + 12}" font-family="Inter, Arial, Helvetica, sans-serif" font-size="24" font-weight="700" fill="#64748b">${label}</text>
          <text x="438" y="${y + 12}" font-family="Inter, Arial, Helvetica, sans-serif" font-size="30" font-weight="800" fill="#0f172a">${value}</text>
        </g>
      `;
    })
    .join("");

  const svg = `
    <svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
      <defs>
        <linearGradient id="accent" x1="0%" y1="0%" x2="100%" y2="0%">
          <stop offset="0%" stop-color="#22d3ee" />
          <stop offset="55%" stop-color="#6366f1" />
          <stop offset="100%" stop-color="#a855f7" />
        </linearGradient>
        <filter id="cardShadow" x="-10%" y="-10%" width="120%" height="120%">
          <feDropShadow dx="0" dy="24" stdDeviation="28" flood-color="#0f172a" flood-opacity="0.12" />
        </filter>
      </defs>
      <rect width="1200" height="630" fill="#f1f5f9" />
      <rect x="76" y="62" width="1048" height="506" fill="#ffffff" stroke="#dbe3ee" filter="url(#cardShadow)" />
      <rect x="76" y="62" width="1048" height="8" fill="url(#accent)" />
      <text x="104" y="126" font-family="Inter, Arial, Helvetica, sans-serif" font-size="18" font-weight="800" fill="#475569" letter-spacing="3">VELMORA HEALTH TOOL</text>
      <text x="104" y="198" font-family="Inter, Arial, Helvetica, sans-serif" font-size="50" font-weight="900" fill="#0f172a">${safeTitle}</text>
      ${resultRows}
      <line x1="104" y1="496" x2="1096" y2="496" stroke="#e2e8f0" stroke-width="2" />
      <rect x="104" y="528" width="54" height="6" fill="url(#accent)" />
      <text x="178" y="538" font-family="Inter, Arial, Helvetica, sans-serif" font-size="22" font-weight="700" fill="#334155">${safeFooter}</text>
    </svg>
  `.trim();

  const blob = new Blob([svg], { type: "image/svg+xml;charset=utf-8" });
  const objectUrl = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = objectUrl;
  link.download = `${filename}.svg`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(objectUrl);
}
